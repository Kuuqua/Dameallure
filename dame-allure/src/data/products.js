export function getProductsByDepartment(departmentSlug) {
  return products.filter((p) => p.department === departmentSlug);
}

export function getProductsBySubcategory(departmentSlug, subcategory) {
  return products.filter(
    (p) => p.department === departmentSlug && p.subcategory === subcategory
  );
}

export function getProductsByOccasion(occasionLabel) {
  return products.filter((p) => p.occasions?.includes(occasionLabel));
}

export function getNewArrivals() {
  return products.filter((p) => p.isNewArrival);
}

export function getProduct(slug) {
  return products.find((p) => p.slug === slug);
}
